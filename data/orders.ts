// Generate a date string for a specific number of days ago
const getDateDaysAgo = (daysAgo: number): string => {
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  return date.toLocaleDateString("en-US", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
};

// Generate a random amount between min and max
const getRandomAmount = (min: number, max: number): string => {
  const amount = Math.floor(min + Math.random() * (max - min));
  return amount.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ".") + " ₫";
};

// Generate a random time string
const getRandomTime = (): string => {
  const hours = Math.floor(Math.random() * 12) + 1;
  const minutes = Math.floor(Math.random() * 60);
  const period = Math.random() > 0.5 ? "AM" : "PM";
  return `${hours}:${minutes.toString().padStart(2, "0")} ${period}`;
};

